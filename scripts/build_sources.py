#!/usr/bin/env python3
"""Compile references/sources.md: a deduplicated master bibliography built from every page's
'## Sources' section plus the source lists in docs/09-reference/.

Source line format (see CLAUDE.md):
  - [Verified] Author, A. & Author, B. (2008). "Title." *Venue*. <https://...> (accessed 2026-11)

Usage: python scripts/build_sources.py
"""
from __future__ import annotations

import re
from collections import OrderedDict

from kb import DOCS, MODULES, ROOT, all_pages, read

OUT = ROOT / "references" / "sources.md"
ENTRY = re.compile(r"^\s*[-*]\s+\[(Verified|Reported|Estimate|Lore)\]\s+(.*)$")
URL = re.compile(r"https?://[^\s>)\]]+")
REF_PAGES = {"books.md", "papers.md", "talks-podcasts-blogs.md", "datasets-and-tools.md"}

STRAT = {
    "a-liquidity-provision": "Liquidity provision", "b-speed-and-structural": "Speed & structural",
    "c-statistical-arbitrage": "Statistical arbitrage", "d-mid-frequency-alpha": "Mid-frequency alpha",
    "e-risk-premia-and-factors": "Risk premia & factors", "f-volatility-and-derivatives": "Volatility & derivatives",
    "g-futures-and-macro-context": "Futures & macro", "h-cross-cutting": "Cross-cutting strategy pages",
}
ALGO = {
    "a-data-and-signals": "Data & signals", "b-forecasting-models": "Forecasting models",
    "c-validation-and-backtesting": "Validation & backtesting", "d-portfolio-construction": "Portfolio construction",
    "e-execution-algorithms": "Execution algorithms", "f-market-making-and-hft-algorithms": "Market making & HFT",
    "g-live-trading": "Live trading", "h-end-to-end-walkthroughs": "Walkthroughs",
}


def group_of(rel: str) -> tuple[str, str]:
    parts = rel.split("/")
    if parts[0] == "02-strategies":
        return "Strategy families", STRAT.get(parts[1], "Strategies (overview)") if len(parts) > 2 else "Strategies (overview)"
    if parts[0] == "03-algorithms":
        return "Algorithm areas", ALGO.get(parts[1], "Algorithms (overview)") if len(parts) > 2 else "Algorithms (overview)"
    title = MODULES.get(parts[0], ("Other", 0))[0]
    return "Other", title


def key_of(text: str) -> str:
    m = URL.search(text)
    if m:
        u = m.group(0).rstrip(".,;").lower().replace("http://", "https://").replace("://www.", "://")
        return u.rstrip("/")
    return re.sub(r"\W+", " ", text.lower()).strip()


def main() -> int:
    entries: "OrderedDict[str, dict]" = OrderedDict()
    for p in all_pages():
        rel = p.relative_to(DOCS).as_posix()
        text = read(p)
        if "<!-- STUB -->" in text:
            continue
        if p.name in REF_PAGES and rel.startswith("09-reference/"):
            block = text
        else:
            m = re.search(r"(?ms)^## Sources\s*$(.*?)(?=^## |\Z)", text)
            if not m:
                continue
            block = m.group(1)
        for line in block.splitlines():
            em = ENTRY.match(line)
            if not em:
                continue
            tag, body = em.group(1), em.group(2).strip()
            k = key_of(body)
            if k not in entries:
                entries[k] = {"tag": tag, "body": body, "group": group_of(rel), "pages": []}
            if rel not in entries[k]["pages"]:
                entries[k]["pages"].append(rel)

    groups: "OrderedDict[tuple[str, str], list]" = OrderedDict()
    order = ["Strategy families", "Algorithm areas", "Other"]
    for e in entries.values():
        groups.setdefault(e["group"], []).append(e)
    tags = {t: sum(1 for e in entries.values() if e["tag"] == t) for t in ("Verified", "Reported", "Estimate", "Lore")}
    lines = [
        "# Master bibliography",
        "",
        "Generated by `scripts/build_sources.py` from the **Sources** section of every page and the "
        "reference lists in `docs/09-reference/`. Do not edit by hand; edit the page and re-run `make sources`.",
        "",
        f"**{len(entries)} unique sources** · " + " · ".join(f"[{t}] {n}" for t, n in tags.items()),
        "",
        "Confidence tags: `[Verified]` primary source · `[Reported]` credible secondary source · "
        "`[Estimate]` derived · `[Lore]` widely repeated, unverified.",
        "",
    ]
    for top in order:
        subs = [g for g in groups if g[0] == top]
        if not subs:
            continue
        lines += [f"## {top}", ""]
        for g in sorted(subs, key=lambda g: g[1]):
            lines += [f"### {g[1]}", ""]
            for e in sorted(groups[g], key=lambda e: e["body"].lower()):
                cites = ", ".join(f"[{p}](../docs/{p})" for p in e["pages"][:4])
                more = f" +{len(e['pages']) - 4} more" if len(e["pages"]) > 4 else ""
                lines.append(f"- [{e['tag']}] {e['body']} — *cited in:* {cites}{more}")
            lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"sources.md: {len(entries)} unique sources -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
