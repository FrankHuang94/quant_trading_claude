"""Price-time-priority limit order book and matching engine (one instrument, one venue).

This is the toy exchange used by the microstructure labs (01-05, 18) and by
``simulate.simulate_lob``. It is small and readable on purpose, but it is a real
matching engine: orders at the same price are served first-in-first-out, a
marketable order sweeps the opposite side from the best price outward, partial
fills leave the remainder resting with its original time priority, and empty
price levels disappear.

Conventions
-----------
* ``side``: ``+1`` = bid / buy, ``-1`` = ask / sell (constants ``BUY``/``BID`` and ``SELL``/``ASK``).
* Prices are floats at the API and **integer ticks internally** (``price / tick`` rounded),
  so there is no floating-point drift in price comparisons.
* Sizes are shares (ints recommended; floats work).
* ``book.time`` is an optional clock you may set before each call; fills are stamped with it.
* Order ids are positive ints assigned in arrival order. Market orders also consume an id
  (it is reported as ``Fill.taker_id``), so replaying the same event sequence on a fresh book
  reproduces the same ids.

Quick example
-------------
>>> book = OrderBook(tick=0.01)
>>> a = book.add_limit(+1, 10.00, 300, owner="A")      # bid 300 @ 10.00
>>> b = book.add_limit(+1, 10.00, 200, owner="B")      # bid 200 @ 10.00, behind A
>>> _ = book.add_limit(-1, 10.02, 400, owner="C")      # ask 400 @ 10.02
>>> book.queue_ahead(b)                                 # A's 300 shares are ahead of B
300
>>> fills = book.market(-1, 400, owner="T")              # sell 400 at market
>>> [(f.maker_owner, f.size, f.price) for f in fills]  # A first (time priority), then B
[('A', 300, 10.0), ('B', 100, 10.0)]
>>> book.order(b).size                                  # B keeps its place with 100 left
100

Complexity: adding/cancelling is O(1) plus an O(#levels) insert when a new price level
appears; matching is O(#orders filled); ``queue_ahead`` is O(queue position). Each price
level is an ``OrderedDict`` (insertion order = time priority, O(1) delete from anywhere).
Roughly 3-6 microseconds per event in CPython, i.e. ~300k events in 1-2 seconds.
"""
from __future__ import annotations

import bisect
from collections import OrderedDict
from dataclasses import dataclass
from collections.abc import Callable
from typing import Any, NamedTuple

BUY = BID = 1
SELL = ASK = -1
_EPS = 1e-9  # sizes below this count as zero (only matters if you use float sizes)


@dataclass(slots=True)
class Fill:
    """One execution between a resting (maker) order and an incoming (taker) order.

    ``price`` is the maker's limit price (price improvement goes to the taker).
    ``taker_side`` is +1 if the taker bought (lifted the ask), -1 if it sold (hit the bid).
    """

    price: float
    size: float
    maker_id: int
    taker_side: int
    maker_owner: Any = None
    taker_owner: Any = None
    time: float | None = None
    taker_id: int | None = None


class OrderInfo(NamedTuple):
    """Read-only view of a resting order (returned by ``OrderBook.order``)."""

    id: int
    side: int
    price: float
    size: float        # remaining (unfilled, uncancelled) size
    orig_size: float   # size when it was submitted (after any immediate crossing)
    owner: Any
    time: float | None


class _Order:
    __slots__ = ("id", "side", "ticks", "price", "size", "orig_size", "owner", "time")

    def __init__(self, oid: int, side: int, ticks: int, price: float, size: float,
                 owner: Any, time: float | None) -> None:
        self.id = oid
        self.side = side
        self.ticks = ticks
        self.price = price
        self.size = size
        self.orig_size = size
        self.owner = owner
        self.time = time


class _Level:
    """All resting orders at one price on one side, in time priority."""

    __slots__ = ("ticks", "orders", "total")

    def __init__(self, ticks: int) -> None:
        self.ticks = ticks
        self.orders: OrderedDict[int, _Order] = OrderedDict()
        self.total = 0


class OrderBook:
    """A price-time-priority limit order book with an integrated matching engine."""

    def __init__(self, tick: float = 0.01) -> None:
        if tick <= 0:
            raise ValueError("tick must be positive")
        self.tick = float(tick)
        self.time: float | None = None          # optional clock, stamped on fills
        self.last_fills: list[Fill] = []        # fills generated by the most recent add/market call
        # For each side, price levels keyed by integer ticks ...
        self._levels: dict[int, dict[int, _Level]] = {BID: {}, ASK: {}}
        # ... and a sorted list of "keys" (side * ticks) so that the BEST level is always keys[-1]
        # (highest bid; for asks the key is -ticks, so the lowest ask has the largest key).
        self._keys: dict[int, list[int]] = {BID: [], ASK: []}
        self._orders: dict[int, _Order] = {}    # resting orders by id
        self._next_id = 1
        self._listeners: list[Callable[[Fill], None]] = []

    # ------------------------------------------------------------------ helpers
    def to_ticks(self, price: float) -> int:
        """Convert a price to integer ticks (rounds to the nearest tick)."""
        return int(round(price / self.tick))

    def to_price(self, ticks: int) -> float:
        """Convert integer ticks back to a (clean) float price."""
        return round(ticks * self.tick, 10)

    @staticmethod
    def _check_side(side: int) -> int:
        if side not in (1, -1):
            raise ValueError(f"side must be +1 (bid/buy) or -1 (ask/sell), got {side!r}")
        return int(side)

    def _new_id(self) -> int:
        oid = self._next_id
        self._next_id += 1
        return oid

    def subscribe(self, callback: Callable[[Fill], None]) -> None:
        """Call ``callback(fill)`` for every future fill (in execution order)."""
        self._listeners.append(callback)

    def unsubscribe(self, callback: Callable[[Fill], None]) -> None:
        self._listeners.remove(callback)

    # ------------------------------------------------------------------ order entry
    def add_limit(self, side: int, price: float, size: float, owner: Any = None) -> int:
        """Submit a limit order and return its id.

        If the order is marketable (a bid at or above the best ask, or an ask at or below the
        best bid) it first trades against the opposite side, up to its limit price; any
        remainder then rests in the book at ``price``. Fills from the crossing part are in
        ``book.last_fills``. ``book.order(id)`` returns None if nothing rests.
        """
        side = self._check_side(side)
        if not size > 0:
            raise ValueError("size must be positive")
        ticks = self.to_ticks(price)
        oid = self._new_id()
        self.last_fills = []
        remaining = size
        opp_keys = self._keys[-side]
        if opp_keys:
            best_opp = -opp_keys[-1] if side == BID else opp_keys[-1]   # ticks of best opposite
            # (for side=BID the opposite is ASK whose keys are -ticks; for side=ASK keys are +ticks)
            if (side == BID and ticks >= best_opp) or (side == ASK and ticks <= best_opp):
                remaining = self._match(side, size, ticks, owner, oid)
        if remaining > _EPS:
            self._rest(oid, side, ticks, remaining, owner)
        return oid

    def market(self, side: int, size: float, owner: Any = None) -> list[Fill]:
        """Market order: +1 buys (lifts asks), -1 sells (hits bids).

        Sweeps the opposite side from the best price outward until ``size`` is filled or the
        book is empty; any unfilled remainder is discarded (immediate-or-cancel). Returns fills.
        """
        side = self._check_side(side)
        if not size > 0:
            raise ValueError("size must be positive")
        self.last_fills = []
        self._match(side, size, None, owner, self._new_id())
        return self.last_fills

    def cancel(self, order_id: int, size: float | None = None) -> bool:
        """Cancel an order entirely (``size=None``) or reduce it by ``size`` shares.

        A size reduction keeps the order's time priority (as on most exchanges). Returns False
        if the order is not resting (unknown, already filled or cancelled).
        """
        o = self._orders.get(order_id)
        if o is None:
            return False
        level = self._levels[o.side][o.ticks]
        if size is None or size >= o.size - _EPS:
            del level.orders[order_id]
            level.total -= o.size
            o.size = 0
            del self._orders[order_id]
            if not level.orders:
                self._remove_level(o.side, o.ticks)
        else:
            if not size > 0:
                raise ValueError("cancel size must be positive")
            o.size -= size
            level.total -= size
        return True

    # ------------------------------------------------------------------ internals
    def _rest(self, oid: int, side: int, ticks: int, size: float, owner: Any) -> None:
        levels = self._levels[side]
        level = levels.get(ticks)
        if level is None:
            level = _Level(ticks)
            levels[ticks] = level
            bisect.insort(self._keys[side], side * ticks)
        o = _Order(oid, side, ticks, self.to_price(ticks), size, owner, self.time)
        level.orders[oid] = o          # joins the BACK of the queue
        level.total += size
        self._orders[oid] = o

    def _remove_level(self, side: int, ticks: int) -> None:
        del self._levels[side][ticks]
        keys = self._keys[side]
        i = bisect.bisect_left(keys, side * ticks)
        del keys[i]

    def _match(self, taker_side: int, size: float, limit_ticks: int | None, owner: Any,
               taker_id: int) -> float:
        """Match an incoming order against the opposite side. Returns the unfilled size."""
        book_side = -taker_side
        keys = self._keys[book_side]
        levels = self._levels[book_side]
        fills = self.last_fills
        listeners = self._listeners
        orders_by_id = self._orders
        while size > _EPS and keys:
            best_ticks = book_side * keys[-1]           # key = side * ticks
            if limit_ticks is not None:
                if taker_side == BUY and best_ticks > limit_ticks:
                    break
                if taker_side == SELL and best_ticks < limit_ticks:
                    break
            level = levels[best_ticks]
            queue = level.orders
            while size > _EPS and queue:
                oid = next(iter(queue))                 # front of the queue (oldest order)
                o = queue[oid]
                q = o.size if o.size <= size else size
                o.size -= q
                level.total -= q
                size -= q
                f = Fill(o.price, q, oid, taker_side, o.owner, owner, self.time, taker_id)
                fills.append(f)
                for cb in listeners:
                    cb(f)
                if o.size <= _EPS:
                    queue.popitem(last=False)
                    del orders_by_id[oid]
            if not queue:                               # level exhausted -> remove it
                del levels[best_ticks]
                keys.pop()
        return size

    # ------------------------------------------------------------------ market data
    def best_bid(self) -> float | None:
        """Highest bid price, or None if there are no bids."""
        k = self._keys[BID]
        return self.to_price(k[-1]) if k else None

    def best_ask(self) -> float | None:
        """Lowest ask price, or None if there are no asks."""
        k = self._keys[ASK]
        return self.to_price(-k[-1]) if k else None

    def best_bid_size(self) -> float:
        k = self._keys[BID]
        return self._levels[BID][k[-1]].total if k else 0

    def best_ask_size(self) -> float:
        k = self._keys[ASK]
        return self._levels[ASK][-k[-1]].total if k else 0

    def mid(self) -> float | None:
        """(best bid + best ask) / 2, or None if either side is empty."""
        kb, ka = self._keys[BID], self._keys[ASK]
        if not kb or not ka:
            return None
        return (kb[-1] - ka[-1]) * self.tick / 2.0

    def spread(self) -> float | None:
        """best ask - best bid in price units, or None if either side is empty."""
        kb, ka = self._keys[BID], self._keys[ASK]
        if not kb or not ka:
            return None
        return self.to_price(-ka[-1] - kb[-1])

    def spread_ticks(self) -> int | None:
        kb, ka = self._keys[BID], self._keys[ASK]
        if not kb or not ka:
            return None
        return -ka[-1] - kb[-1]

    def imbalance(self, levels: int = 1) -> float | None:
        """(bid size - ask size) / (bid size + ask size) over the top ``levels`` levels."""
        b = sum(s for _, s in self.depth(BID, levels))
        a = sum(s for _, s in self.depth(ASK, levels))
        return (b - a) / (b + a) if (a + b) > 0 else None

    def depth(self, side: int, levels: int = 5) -> list[tuple[float, float]]:
        """[(price, total size), ...] for the best ``levels`` price levels, best first."""
        side = self._check_side(side)
        keys = self._keys[side]
        lv = self._levels[side]
        out = []
        for key in reversed(keys[-levels:] if levels > 0 else []):
            t = side * key
            out.append((self.to_price(t), lv[t].total))
        return out

    def level_orders(self, side: int, price: float) -> list[OrderInfo]:
        """Resting orders at one price, in queue (time-priority) order: front first."""
        level = self._levels[self._check_side(side)].get(self.to_ticks(price))
        if level is None:
            return []
        return [self._info(o) for o in level.orders.values()]

    def queue_ahead(self, order_id: int) -> float | None:
        """Shares resting ahead of this order at its price level (None if not resting)."""
        o = self._orders.get(order_id)
        if o is None:
            return None
        ahead = 0
        for oid, other in self._levels[o.side][o.ticks].orders.items():
            if oid == order_id:
                break
            ahead += other.size
        return ahead

    @staticmethod
    def _info(o: _Order) -> OrderInfo:
        return OrderInfo(o.id, o.side, o.price, o.size, o.orig_size, o.owner, o.time)

    def order(self, order_id: int) -> OrderInfo | None:
        """Read-only view of a resting order, or None if it is no longer in the book."""
        o = self._orders.get(order_id)
        return None if o is None else self._info(o)

    def is_resting(self, order_id: int) -> bool:
        return order_id in self._orders

    @property
    def n_orders(self) -> int:
        """Number of resting orders (both sides)."""
        return len(self._orders)

    def snapshot(self, levels: int = 5) -> dict:
        """Dict with time, best_bid/ask, mid, spread, imbalance and the top ``levels`` levels."""
        return {
            "time": self.time,
            "best_bid": self.best_bid(),
            "best_ask": self.best_ask(),
            "mid": self.mid(),
            "spread": self.spread(),
            "imbalance": self.imbalance(1),
            "bids": self.depth(BID, levels),
            "asks": self.depth(ASK, levels),
        }

    def _top3(self) -> tuple:
        """Fast internal accessor used by the simulator: best prices (ticks) and top-3 sizes."""
        kb, ka = self._keys[BID], self._keys[ASK]
        lb, la = self._levels[BID], self._levels[ASK]
        nb, na = len(kb), len(ka)
        b1 = kb[-1] if nb else None
        a1 = -ka[-1] if na else None
        return (
            b1, a1,
            lb[b1].total if nb else 0, lb[kb[-2]].total if nb > 1 else 0, lb[kb[-3]].total if nb > 2 else 0,
            la[a1].total if na else 0, la[-ka[-2]].total if na > 1 else 0, la[-ka[-3]].total if na > 2 else 0,
        )

    def to_string(self, levels: int = 5, show_orders: bool = True) -> str:
        """Human-readable ladder: asks on top (worst to best), then bids (best to worst).

        With ``show_orders`` each level lists its queue front-to-back as owner:size.
        """
        lines = []
        def fmt_level(side: int, price: float, total: float) -> str:
            q = ""
            if show_orders:
                q = "  [" + ", ".join(f"{o.owner}:{o.size:g}" for o in self.level_orders(side, price)) + "]"
            tag = "ASK" if side == ASK else "BID"
            return f"   {tag} {price:>10.2f} {total:>8g}{q}"
        for p, s in reversed(self.depth(ASK, levels)):
            lines.append(fmt_level(ASK, p, s))
        sp = self.spread()
        lines.append(f"   --- spread {sp:.2f} ---" if sp is not None else "   --- (one side empty) ---")
        for p, s in self.depth(BID, levels):
            lines.append(fmt_level(BID, p, s))
        return "\n".join(lines)

    def __repr__(self) -> str:
        return (f"OrderBook(tick={self.tick}, bid={self.best_bid()}, ask={self.best_ask()}, "
                f"orders={self.n_orders})")


